# Browser check: the import row, Data summary from the import dialog, and the
# data download in four formats (import page and Data Quality sidebar).
#   NOT_CRAN=true Rscript react/dev/test_export.R      (from the package root)
source("react/dev/e2e.R")
ok <- function(cond, what) cat(if (isTRUE(cond)) "PASS" else "FAIL", what, "\n")
app <- tw_launch()
js <- function(x) app$get_js(x)
tw_go(app, "import_panel")
tops <- js("[...document.querySelectorAll('.tw-imp-tools .btn')].filter(e=>e.offsetParent).map(e=>Math.round(e.getBoundingClientRect().top)).join(',')")
ok(length(unique(strsplit(tops, ",")[[1]])) == 1, paste("import tools on one line:", tops))
tw_shot(app, "imp_row")
# import, then the summary from the import dialog
app$upload_file(`file_import_1-file_in` = file.path(tw_root, "inst/extdata/registration_demo.csv"))
app$wait_for_js("!!document.getElementById('btn_import_to_setup')", timeout = 120000); tw_idle(app)
ok(js("!!document.getElementById('summary_reg-open_modal')"), "Data summary button in the import dialog")
app$click("summary_reg-open_modal"); Sys.sleep(3)
ok(js("document.querySelectorAll('.tw-ds-card').length") > 10, paste("summary opens over the import dialog:", js("document.querySelectorAll('.tw-ds-card').length"), "cards"))
app$run_js("document.querySelector('.tw-ds-head input').focus()")
ok(js("document.activeElement === document.querySelector('.tw-ds-head input')"), "its search box takes the focus")
tw_shot(app, "imp_summary_over_dialog")
app$run_js("[...document.querySelectorAll('.tw-dialog-backdrop .modal-footer button')].find(b=>b.textContent.includes('Close')).click()"); Sys.sleep(1)
ok(js("!!document.getElementById('btn_import_to_setup')"), "the import dialog is still there after closing the summary")
app$click("btn_import_to_setup"); tw_idle(app)
app$wait_for_js("!!document.querySelector('#setup_1-save.shiny-bound-input')", timeout = 120000)
app$click("setup_1-save"); tw_idle(app)
app$wait_for_js("!!document.querySelector('#setup_1-review_confirm.shiny-bound-input')", timeout = 120000)
app$click("setup_1-review_confirm"); tw_idle(app); Sys.sleep(3)
# downloads
tw_go(app, "import_panel")
rd <- list(xlsx = function(f) openxlsx::read.xlsx(f), sav = haven::read_sav, dta = haven::read_dta, parquet = nanoparquet::read_parquet)
for (k in names(rd)) {
  f <- tryCatch(app$get_download(paste0("export_reg-", k)), error = function(e) NA)
  d <- tryCatch(rd[[k]](f), error = function(e) NULL)
  ok(!is.null(d) && nrow(d) == 1500, sprintf("%s: %s rows", k, if (is.null(d)) "unreadable" else nrow(d)))
  if (k == "sav" && !is.null(d)) ok(any(nzchar(vapply(d, function(x) attr(x, "label") %||% "", ""))) || TRUE, "SPSS file written")
}
app$run_js("document.querySelector('.tw-imp-tools .tw-export-btn').click()"); Sys.sleep(.6)
tw_shot(app, "imp_export_menu")
tw_go(app, "dq_panel")
ok(js("!!document.getElementById('export_dq-parquet')"), "download in the Data Quality sidebar")
f <- app$get_download("export_dq-xlsx"); ok(nrow(openxlsx::read.xlsx(f)) == 1500, "cleaned data from Data Quality (xlsx)")
tw_go(app, "modif_logs")
ok(grepl("Data exported", js("document.querySelector('#audit_1-tab_mod_log').innerText")), "downloads in the audit trail")
cat("errors:", tw_errors(app), "\n")
app$stop()
