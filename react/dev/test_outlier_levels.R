# Browser check: Outliers compares areas at any mapped level (Admin 1 to 4, village).
#   NOT_CRAN=true Rscript react/dev/test_outlier_levels.R      (from the package root)
source("react/dev/e2e.R")
ok <- function(cond, what) cat(if (isTRUE(cond)) "PASS" else "FAIL", what, "\n")
app <- tw_launch()
js <- function(x) app$get_js(x)
NS <- "dq_1-"
wait <- function(s = 1) { Sys.sleep(s); tw_idle(app); Sys.sleep(.6) }
setv <- function(id, value) app$run_js(sprintf("(function(){var el=document.querySelector('.shiny-bound-input#%s'); $(el).data('shiny-input-binding').receiveMessage(el, {value: %s});})()", paste0(NS, id), jsonlite::toJSON(value, auto_unbox = TRUE)))
tab <- function(lbl) app$run_js(sprintf("[...document.querySelectorAll('.tw-tabs-nav button')].find(b=>b.textContent.includes('%s')).click()", lbl))
cats <- function(id) js(sprintf("(function(){var c=document.querySelector('#%s%s .tw-echart'); if(!c) return -1; var i=echarts? 0:0; return c.getAttribute('data-n')||0})()", NS, id))
tw_load_registration(app)
tw_go(app, "dq_panel"); tab("Outliers"); wait(3)
setv("outlier_var", "HHSize"); wait(3)
opts <- js("JSON.stringify((window.__lv = [...document.querySelectorAll('.tw-dq-toolbar label')].map(l=>l.textContent)))")
ok(grepl("Compare areas by", opts), "the level picker is in the toolbar")
title <- function(sel) js(sprintf("[...document.querySelectorAll('.tw-card .tw-card-title')].map(e=>e.textContent).filter(t=>t.includes('%s')).join(' | ')", sel))
ok(grepl("Admin 1", title("By area")), paste("starts at Admin 1:", title("By area")))
setv("ol_level", "admin2"); wait(3)
ok(grepl("Admin 2", title("By area")), paste("box plot at Admin 2:", title("By area")))
tab("Where they come from"); wait(2)
ok(grepl("Admin 2", title("Flag rate by area")), paste("rates at Admin 2:", title("Flag rate by area")))
tw_shot(app, "ol_admin2")
setv("ol_level", "village"); wait(3)
ok(grepl("Village", title("Flag rate by area")), paste("rates at Village:", title("Flag rate by area")))
err <- js("[...document.querySelectorAll('#dq_1-plot_outlier_admin_rates .tw-output-note')].map(e=>e.textContent).join('')")
ok(!nzchar(err) || grepl("at least 5", err), paste("village rates drawn (or the minimum explained):", err))
tab("Distribution"); wait(2)
ok(grepl("Village", title("By area")), paste("box plot at Village:", title("By area")))
tw_shot(app, "ol_village")
cat("errors:", tw_errors(app), "\n")
app$stop()
